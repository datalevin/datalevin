(defn bytes->hex [^bytes bytes] (.formatHex (HexFormat/of) bytes))
(defn hex->bytes ^bytes [^String hex] (.parseHex (HexFormat/of) hex))

(defn bitmap [values]
  (let [bitmap (RoaringBitmap.)]
    (doseq [n values] (.add bitmap (unchecked-int n)))
    bitmap))

(defn growing [values]
  (doto (GrowingIntArray.) (.addAll (int-array values))))

