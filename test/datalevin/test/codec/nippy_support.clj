(defn stress-fixtures
  "Every upstream leaf and the complete map, without type exclusions."
  []
  (let [data (nippy/stress-data {:comparable? false})]
    (into {"stress/complete" data}
          (concat
           (for [[k v] (dissoc data :non-comparable)] [(str "stress/" (name k)) v])
           (for [[k v] (dissoc (:non-comparable data) :arrays)] [(str "stress/non-comparable/" (name k)) v])
           (for [[k v] (get-in data [:non-comparable :arrays])] [(str "stress/arrays/" (name k)) v])))))

(defn fixtures [] (merge (native-fixtures) (stress-fixtures)))

(defn write-vectors!
  "Regenerate the checked-in corpus using the JVM's resolved Nippy version."
  [path]
  (let [rows (for [[id value] (sort-by key (fixtures))]
               (str id "\t" (bytes->hex (nippy/fast-freeze value))))]
    (spit path (str "# JVM Nippy fast-freeze; generated by nippy-support/write-vectors!\n"
                    (str/join "\n" rows) "\n"))))

(defn value=
  "Checks upstream values, including arrays and exceptions that lack value equality."
  [left right]
  (cond
    (and (instance? Throwable left) (instance? Throwable right))
    (and (= (class left) (class right))
         (= (.getMessage ^Throwable left) (.getMessage ^Throwable right))
         (value= (ex-data left) (ex-data right))
         (value= (.getCause ^Throwable left) (.getCause ^Throwable right))
         (java.util.Arrays/equals (.getStackTrace ^Throwable left)
                                  (.getStackTrace ^Throwable right)))

    (and (some? left) (some? right)
         (.isArray ^Class (class left)) (.isArray ^Class (class right)))
    (java.util.Objects/deepEquals left right)

    (and (map? left) (map? right))
    (and (= (set (keys left)) (set (keys right)))
         (= (meta left) (meta right))
         (every? (fn [[k v]] (value= v (get right k))) left))

    (and (sequential? left) (sequential? right))
    (and (= (count left) (count right)) (every? true? (map value= left right)))

    (and (instance? java.util.regex.Pattern left) (instance? java.util.regex.Pattern right))
    (and (= (.pattern ^java.util.regex.Pattern left) (.pattern ^java.util.regex.Pattern right))
         (= (.flags ^java.util.regex.Pattern left) (.flags ^java.util.regex.Pattern right)))

    :else (= left right)))
